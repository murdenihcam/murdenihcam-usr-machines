#!/usr/bin/env python3
"""Write tables.inc, the constant tables used by ram_gran.asm56k.

  PITCH  2^(n/12) / 4 for n = 0..12 (one octave of semitones, plus its top)
  DECAY  envelope multiplier per 32-sample block for DEC 0..127 (as on RAM-ST)
  AMP    grain peak for DENS 0..127: overlap ov = 0.5 + 2.5 * DENS / 127, peak min(1, 2 / (ov + 1))
  IVL    spawn interval as a share of the grain length, 1 / (2 ov) (doubled on the DSP)
  RECIP  1 / (32 m) for m = 0..MMAX: the triangle's step per sample for a grain of 2m blocks
"""
from pathlib import Path

DEC_MIN_S, DEC_MAX_S = 0.03, 30.0
MMAX = 80
PITCH = [round(2 ** (n / 12) / 4 * 2 ** 23) for n in range(13)]
DECAY = [min(0x7FFFFF, round(10 ** (-3 * 32 / (44100 * DEC_MIN_S * (DEC_MAX_S / DEC_MIN_S) ** (d / 126)))
                             * 2 ** 23)) for d in range(127)] + [0x7FFFFF]
OV = [0.5 + 2.5 * d / 127 for d in range(128)]
AMP = [min(0x7FFFFF, round(min(1.0, 2 / (ov + 1)) * 2 ** 23)) for ov in OV]
IVL = [min(0x7FFFFF, round(1 / (2 * ov) * 2 ** 23)) for ov in OV]
RECIP = [0] + [round(2 ** 23 / (32 * m)) for m in range(1, MMAX + 1)]
PITCH_AT = 0
DECAY_AT = PITCH_AT + len(PITCH)
AMP_AT = DECAY_AT + len(DECAY)
IVL_AT = AMP_AT + len(AMP)
RECIP_AT = IVL_AT + len(IVL)


def dc(values):
    return ["        dc      " + ",".join("$%06x" % v for v in values[i:i + 8]) for i in range(0, len(values), 8)]


if __name__ == "__main__":
    lines = ["; Generated by gen_tables.py: do not edit.",
             f"TB_PITCH equ {PITCH_AT}", f"TB_DECAY equ {DECAY_AT}", f"TB_AMP  equ {AMP_AT}",
             f"TB_IVL  equ {IVL_AT}", f"TB_RECIP equ {RECIP_AT}", f"MMAX    equ {MMAX}",
             "TABLES:", "; pitch 2^(n/12)/4"] + dc(PITCH) + ["; decay per block"] + dc(DECAY) \
        + ["; grain peak for DENS"] + dc(AMP) + ["; spawn interval / (2 * grain length)"] + dc(IVL) \
        + ["; 1 / (32 m)"] + dc(RECIP)
    Path(__file__).with_name("tables.inc").write_text("\n".join(lines) + "\n")
    print("wrote tables.inc")

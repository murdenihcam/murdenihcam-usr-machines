#!/usr/bin/env python3
"""Write tables.inc, the constant tables used by ram_pshift.asm56k.

  PITCH  2^(n/12) / 4 for n = 0..12 (one octave of semitones, plus its top)
  WIN    window W in frames for WIN 0..127: 512 * 32^(WIN / 127) (12 ms .. 370 ms)
  WINR   32 / W (Q23): a block's share of the window
  TONE   one-pole low-pass coefficient for TONE 0..127: 127 = open, 0 = about 400 Hz
"""
import math
from pathlib import Path

PITCH = [round(2 ** (n / 12) / 4 * 2 ** 23) for n in range(13)]
WIN = [round(512 * 32 ** (w / 127)) for w in range(128)]
WINR = [round(32 / w * 2 ** 23) for w in WIN]
TONE = [min(0x7FFFFF, round((1 - math.exp(-2 * math.pi * 400 * 50 ** (t / 127) / 44100)) * 2 ** 23))
        for t in range(127)] + [0x7FFFFF]


def dc(values):
    return ["        dc      " + ",".join("$%06x" % v for v in values[i:i + 8]) for i in range(0, len(values), 8)]


if __name__ == "__main__":
    at = {}
    pos = 0
    for name, t in (("PITCH", PITCH), ("WIN", WIN), ("WINR", WINR), ("TONE", TONE)):
        at[name] = pos
        pos += len(t)
    lines = ["; Generated by gen_tables.py: do not edit."] + [f"TB_{k:5s} equ {v}" for k, v in at.items()] \
        + ["TABLES:", "; pitch"] + dc(PITCH) + ["; window frames"] + dc(WIN) + ["; 32 / window"] + dc(WINR) \
        + ["; tone low-pass coefficient"] + dc(TONE)
    Path(__file__).with_name("tables.inc").write_text("\n".join(lines) + "\n")
    print("wrote tables.inc")
